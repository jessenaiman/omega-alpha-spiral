/** Points along an ellipse. 0 rad = right, PI/2 = down. */
const arc = (
  cx: number,
  cy: number,
  rx: number,
  ry: number,
  a0: number,
  a1: number,
  n = 12
): number[] => {
  const p: number[] = [];
  for (let i = 0; i <= n; i++) {
    const a = a0 + (a1 - a0) * (i / n);
    p.push(cx + Math.cos(a) * rx, cy + Math.sin(a) * ry);
  }
  return p;
};

/** Full ellipse. */
const ring = (cx: number, cy: number, rx: number, ry: number, n = 16) =>
  arc(cx, cy, rx, ry, 0, Math.PI * 2, n);

/** Semicircle bulging right, attached to a stem at x. */
const bowl = (x: number, y0: number, y1: number, rx = 0.4) =>
  arc(x, (y0 + y1) / 2, rx, (y1 - y0) / 2, -Math.PI / 2, Math.PI / 2, 10);

/** Semicircle bulging left, attached at y0/y1 to the right of x. */
const backBowl = (x: number, y0: number, y1: number, rx = 0.4) =>
  arc(x, (y0 + y1) / 2, rx, (y1 - y0) / 2, Math.PI / 2, Math.PI * 1.5, 10);

/** Open-on-the-right C shape. */
const cee = (cx: number, y0: number, y1: number, rx = 0.38) =>
  arc(
    cx,
    (y0 + y1) / 2,
    rx,
    (y1 - y0) / 2,
    -Math.PI / 3,
    -Math.PI * (5 / 3),
    14
  );

/** Top arch joining two stems. */
const arch = (cx: number, y: number, rx: number, ry: number) =>
  arc(cx, y, rx, ry, Math.PI, Math.PI * 2, 10);

